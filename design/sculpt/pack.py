"""Bake every character to client/sculpt-v2-data.mjs (quantised binary in base64)."""
import importlib,json,base64,numpy as np,sys
from sdf import polygonize,colours,union
from export import surface_point
ORDER=['pof','robot','cat','cyclops','dragon','jelly','star']
STEP={'head':.02,'torso':.021,'armL':.02,'armR':.02,'legL':.02,'legR':.02}
def pack_part(spec):
    p=spec['part'];p.step=STEP.get(p.name,.016) if spec.get('group')!='accessory' else p.step
    v,n,f=polygonize(p,lo=(-1.6,-1.2,-1.6),hi=(1.6,2.2,1.8));rgb,tint,shade=colours(p,v)
    lo=v.min(0);hi=v.max(0);q=np.round((v-lo)/np.maximum(hi-lo,1e-6)*65535).astype('<u2')
    nn=np.clip(np.round(n*127),-127,127).astype('i1')
    col=np.clip(np.round(np.column_stack([rgb,tint,np.clip(shade/1.25,0,1)])*255),0,255).astype('u1')
    assert len(v)<65536
    dq=np.diff(np.vstack([np.zeros((1,3),dtype=np.int64),q.astype(np.int64)]),axis=0)
    dq=(dq%65536).astype('<u2')
    fi=f.astype(np.int64).ravel();df=(np.diff(np.concatenate([[0],fi]))%65536).astype('<u2')
    # planar layout groups similar bytes so gzip/zip can find them
    blob=dq.T.copy().tobytes()+nn.T.copy().tobytes()+col.T.copy().tobytes()+df.tobytes()
    return {'name':p.name,'group':spec.get('group','head'),'pivot':spec.get('pivot'),'material':spec.get('material','skin'),
            'count':int(len(v)),'tris':int(len(f)),'min':np.round(lo,5).tolist(),'max':np.round(hi,5).tolist(),
            'data':base64.b64encode(blob).decode()}
HAT={'Pof':((0,-.02),(.3,.27),.15),'Robot':((0,0),(.36,.27),.13),'Cat':((0,0),(.17,.15),.06),'Cyclops':((0,-.02),(.17,.15),.06),
     'Dragon':((0,-.02),(.14,.13),.05),'Jelly':((0,0),(.3,.27),.12),'Star':((0,0),(.11,.09),.07)}
NECK={'Pof':.52,'Robot':.49,'Cat':.52,'Cyclops':.52,'Dragon':.52,'Jelly':.48,'Star':.42}
def top_at(shape,x,z):
    y=2.2
    for _ in range(300):
        d=shape(np.array([[x,y,z]]))[0]
        if d<1e-4:return y
        y-=max(d,1e-3)
        if y<0:return None
    return y
def fits(ch):
    head=ch['face_shape'];(cx,cz),(rx,rz),depth=HAT[ch['name']]
    tops=[top_at(head,cx+rx*u,cz+rz*v) for u in np.linspace(-1,1,9) for v in np.linspace(-1,1,9) if u*u+v*v<=1]
    top=max(t for t in tops if t is not None)
    body=union(*[sp['part'].shape for sp in ch['parts'] if sp.get('group') in (('torso',) if ch['name']=='Jelly' else ('head','torso'))])
    ny=NECK[ch['name']];xs=np.linspace(-.6,.6,241);zs=np.linspace(-.6,.6,241);G=np.stack(np.meshgrid(xs,zs,indexing='ij'),-1).reshape(-1,2)
    P=np.concatenate([np.column_stack([G[:,0],np.full(len(G),y),G[:,1]]) for y in (ny-.05,ny,ny+.05)]);inside=P[body(P)<0]
    hx=float(np.abs(inside[:,0]).max());z0,z1=float(inside[:,2].min()),float(inside[:,2].max())
    fy,fz=ny,z1
    if ch['name']=='Jelly':
        fy=.66;zz=np.linspace(-.6,.8,701);Q=np.column_stack([np.zeros_like(zz),np.full_like(zz,fy),zz]);fz=float(Q[head(Q)<0][:,2].max())
    return {'hat':{'at':[cx,round(top-depth,4),cz],'size':[rx,rx,rz],'top':round(top,4)},
            'neck':{'y':ny,'fy':fy,'front':round(fz,4),'rx':round(hx,4),'rz':round((z1-z0)/2,4),'cz':round((z0+z1)/2,4)}}
out=[]
for c in ORDER:
    ch=importlib.import_module(c).build()
    parts=[pack_part(s) for s in ch['parts']]
    anchors={k:[np.round(a,4).tolist() for a in surface_point(ch['face_shape'],x,y)] for k,(x,y) in ch['anchors'].items()}
    out.append({'fits':fits(ch),'name':ch['name'],'base':ch['base'],'eyes':ch['eyes'],'anchors':anchors,'pivots':ch.get('pivots',{}),'materials':ch.get('materials',{}),'parts':parts})
    print(c,sum(p['count'] for p in parts),'verts',sum(p['tris'] for p in parts),'tris',file=sys.stderr)
import accessories as A
wardrobe={}
for k,fn in A.ITEMS.items():
    part=fn();wrap=k in A.HEAD or k in ('scarf','bellCollar');part.step=.075 if wrap else .012
    spec=pack_part({'part':part,'group':'accessory'});spec['kind']='head' if k in A.HEAD else 'wrap' if wrap else 'front';wardrobe[k]=spec
    print(k,spec['count'],file=sys.stderr)
js='// Generated by design/sculpt/pack.py; do not edit by hand.\nexport const SCULPT_V2='+json.dumps(out,separators=(',',':'))+';\nexport const WARDROBE_V2='+json.dumps(wardrobe,separators=(',',':'))+';\n'
open(sys.argv[1],'w').write(js);print(len(js)//1024,'KB',file=sys.stderr)
